import { expect, test } from '@playwright/test'
import { mockApi, postsOf } from './api'

test('publishes a post optimistically, keeps it per user and across a reload', async ({ page }) => {
  await mockApi(page, { createDelayMs: 600 })
  await page.goto('/users/1')
  await expect(page.getByText('3 posts')).toBeVisible()
  await page.getByLabel('Title').fill('  Written   in the browser ')
  await page.getByLabel('Body').fill('Through Playwright.\r\n\r\n\r\nWith blank lines collapsed.')
  await page.getByRole('button', { name: 'Publish' }).click()
  await expect(page.getByText('4 posts')).toBeVisible()
  await expect(page.getByText('Sending…')).toBeVisible()
  await expect(page.getByLabel('Title')).toHaveValue('')
  await expect(page.getByText('New')).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Published.' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Posts' }).getByRole('listitem').first()).toContainText('Written in the browser')
  await page.getByRole('button', { name: 'Show posts by Ervin Howell' }).click()
  await expect(page.getByText('3 posts')).toBeVisible()
  await expect(page.getByText('Written in the browser')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show posts by Leanne Graham' }).click()
  await expect(page.getByText('4 posts')).toBeVisible()
  await page.reload()
  await expect(page.getByText('4 posts')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Posts' }).getByRole('listitem').first()).toContainText('Written in the browser')
})

test('takes the post back and restores the draft when the server refuses it', async ({ page }) => {
  await mockApi(page, { createStatus: 500 })
  await page.goto('/users/2')
  await expect(page.getByText('3 posts')).toBeVisible()
  await page.getByLabel('Title').fill('Doomed')
  await page.getByLabel('Body').fill('Never lands')
  await page.getByRole('button', { name: 'Publish' }).click()
  await expect(page.getByRole('alert')).toContainText('The server answered with an error (500).')
  await expect(page.getByText('3 posts')).toBeVisible()
  await expect(page.getByText('Doomed')).toHaveCount(0)
  await expect(page.getByLabel('Title')).toHaveValue('Doomed')
  await page.unrouteAll()
  await mockApi(page)
  await page.getByRole('button', { name: 'Retry' }).click()
  await expect(page.getByText('4 posts')).toBeVisible()
  await expect(page.getByRole('region', { name: 'Posts' }).getByRole('listitem').first()).toContainText('Doomed')
})

test('refuses an empty or oversized draft without calling the server', async ({ page }) => {
  await mockApi(page)
  await page.goto('/users/3')
  await expect(page.getByText('3 posts')).toBeVisible()
  await page.getByRole('button', { name: 'Publish' }).click()
  await expect(page.getByLabel('Title')).toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByLabel('Title')).toBeFocused()
  await page.getByLabel('Title').fill('🇪🇸'.repeat(101))
  await expect(page.getByText('101/100')).toBeVisible()
  await page.getByLabel('Body').fill('fine')
  await page.getByRole('button', { name: 'Publish' }).click()
  await expect(page.getByText('Keep it under 100 characters.')).toBeVisible()
  await expect(page.getByText('3 posts')).toBeVisible()
})

test('shows the posts failure with a retry, and pages a long list', async ({ page }) => {
  await mockApi(page, { postsStatus: 500 })
  await page.goto('/users/1')
  await expect(page.getByRole('alert')).toContainText('error (500)')
  await page.unrouteAll()
  await mockApi(page, { postCount: { 1: 45 } })
  await page.getByRole('button', { name: 'Retry' }).click()
  await expect(page.getByText('45 posts')).toBeVisible()
  await expect(page.getByRole('heading', { level: 4 })).toHaveCount(20)
  await page.getByRole('button', { name: 'Show 20 more' }).click()
  await expect(page.getByRole('heading', { level: 4 })).toHaveCount(40)
  await page.getByRole('button', { name: 'Show 5 more' }).click()
  await expect(page.getByRole('heading', { level: 4 })).toHaveCount(45)
  await expect(page.getByRole('heading', { level: 4 }).last()).toContainText(postsOf(1, 45)[44]?.title ?? '')
})
