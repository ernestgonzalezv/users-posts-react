import { expect, test } from '@playwright/test'
import { mockApi } from './api'

test('lists the users, keeps the chosen one in the address and survives a reload', async ({ page }) => {
  await mockApi(page)
  await page.goto('/')
  await expect(page.getByRole('main')).toContainText('Pick a user')
  await expect(page.getByText('3 users')).toBeVisible()
  await page.getByRole('button', { name: 'Show posts by Ervin Howell' }).click()
  await expect(page).toHaveURL(/\/users\/2$/)
  await expect(page.getByRole('heading', { level: 2, name: 'Ervin Howell' })).toBeVisible()
  await expect(page.getByText('3 posts')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { level: 2, name: 'Ervin Howell' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Show posts by Ervin Howell' })).toHaveAttribute('aria-pressed', 'true')
  await page.goBack()
  await expect(page.getByRole('main')).toContainText('Pick a user')
})

test('searches by name or username ignoring accents and clears', async ({ page }) => {
  await mockApi(page)
  await page.goto('/')
  const box = page.getByRole('searchbox', { name: 'Search users' })
  await box.fill('ÉRVIN')
  await expect(page.getByText('1 of 3')).toBeVisible()
  await expect(page.getByRole('button', { name: /^Show posts by/ })).toHaveCount(1)
  await box.fill('nobody')
  await expect(page.getByRole('heading', { level: 3, name: 'No one matches “nobody”' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear search' }).click()
  await expect(page.getByRole('button', { name: /^Show posts by/ })).toHaveCount(3)
  await expect(box).toHaveValue('')
})

test('explains an address that names nobody and offers the way back', async ({ page }) => {
  await mockApi(page)
  await page.goto('/users/999')
  await expect(page.getByRole('heading', { level: 3, name: 'That user is not here' })).toBeVisible()
  await page.getByRole('button', { name: 'Back to the list' }).click()
  await expect(page).toHaveURL(/\/$/)
  await expect(page.getByRole('main')).toContainText('Pick a user')
})

test('shows the directory failure with a retry that recovers', async ({ page }) => {
  await mockApi(page, { usersStatus: 503 })
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('The server answered with an error (503).')
  await page.unrouteAll()
  await mockApi(page)
  await page.getByRole('button', { name: 'Retry' }).click()
  await expect(page.getByText('3 users')).toBeVisible()
})

test('switches language and theme and remembers both', async ({ page }) => {
  await mockApi(page)
  await page.goto('/users/1')
  await page.getByRole('radio', { name: 'Spanish' }).click()
  await expect(page.getByRole('heading', { level: 2, name: 'Usuarios' })).toBeVisible()
  await expect(page.getByRole('main')).toContainText('Trabaja en Romaguera-Crona')
  await page.getByRole('radio', { name: 'Oscuro' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.getByRole('heading', { level: 2, name: 'Usuarios' })).toBeVisible()
  await page.getByRole('radio', { name: 'Sistema' }).click()
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})

test('stacks the layout on a phone and scrolls to the posts @mobile', async ({ page }) => {
  await mockApi(page)
  await page.goto('/')
  await page.getByRole('button', { name: 'Show posts by Clementine Bauch' }).click()
  await expect(page.getByRole('heading', { level: 2, name: 'Clementine Bauch' })).toBeInViewport()
  await expect(page.getByRole('main')).toHaveCSS('min-height', /\d/)
  const layout = await page.locator('aside').boundingBox()
  const main = await page.getByRole('main').boundingBox()
  expect(main?.y ?? 0).toBeGreaterThanOrEqual((layout?.y ?? 0) + (layout?.height ?? 0) - 2)
  expect(main?.x ?? 1).toBe(layout?.x ?? 0)
})
